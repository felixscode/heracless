//! Rust struct generation (for using the same YAML config from Rust via serde).

use std::collections::HashSet;
use std::fmt::Write;

use crate::schema::{Schema, Ty};

const RUST_KEYWORDS: &[&str] = &[
    "as", "async", "await", "break", "const", "continue", "crate", "dyn", "else", "enum", "extern",
    "false", "fn", "for", "gen", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut",
    "pub", "ref", "return", "self", "Self", "static", "struct", "super", "trait", "true", "type",
    "unsafe", "use", "where", "while", "abstract", "become", "box", "do", "final", "macro",
    "override", "priv", "try", "typeof", "unsized", "virtual", "yield",
];

/// Keywords that can't be raw identifiers (`r#self` is invalid).
const NON_RAW: &[&str] = &["crate", "self", "Self", "super"];

fn field_ident(name: &str) -> String {
    if NON_RAW.contains(&name) {
        format!("{name}_")
    } else if RUST_KEYWORDS.contains(&name) {
        format!("r#{name}")
    } else {
        name.to_string()
    }
}

fn type_ident(name: &str) -> String {
    if NON_RAW.contains(&name) || RUST_KEYWORDS.contains(&name) {
        format!("{name}_")
    } else {
        name.to_string()
    }
}

struct Renderer<'a> {
    schema: &'a Schema,
    /// Generated type names; std types they shadow are written fully qualified.
    names: HashSet<String>,
}

impl Renderer<'_> {
    fn std(&self, short: &str, path: &str) -> String {
        if self.names.contains(short) {
            path.to_string()
        } else {
            short.to_string()
        }
    }

    fn render(&self, ty: &Ty) -> String {
        let dynamic = "serde_json::Value".to_string();
        match ty {
            Ty::Any => dynamic,
            Ty::None => format!("{}<{dynamic}>", self.std("Option", "::std::option::Option")),
            Ty::Bool => "bool".into(),
            Ty::Int => "i64".into(),
            Ty::Float => "f64".into(),
            // Dates are kept as their ISO 8601 text.
            Ty::Str | Ty::Date | Ty::DateTime => self.std("String", "::std::string::String"),
            Ty::List(element) => format!(
                "{}<{}>",
                self.std("Vec", "::std::vec::Vec"),
                self.render(element)
            ),
            Ty::Class(id) => type_ident(&self.schema.class(*id).name),
            Ty::Union(members) => {
                let non_null: Vec<&Ty> = members.iter().filter(|m| **m != Ty::None).collect();
                let inner = match non_null.as_slice() {
                    [single] => self.render(single),
                    _ => dynamic,
                };
                if non_null.len() < members.len() {
                    format!("{}<{inner}>", self.std("Option", "::std::option::Option"))
                } else {
                    inner
                }
            }
        }
    }
}

fn uses_dynamic(ty: &Ty) -> bool {
    match ty {
        Ty::Any | Ty::None => true,
        Ty::List(element) => uses_dynamic(element),
        Ty::Union(members) => {
            let non_null: Vec<&Ty> = members.iter().filter(|m| **m != Ty::None).collect();
            match non_null.as_slice() {
                [single] => uses_dynamic(single),
                _ => true,
            }
        }
        _ => false,
    }
}

/// Generate serde-deserializable Rust structs for a schema.
///
/// The output needs `serde` (with `derive`), plus `serde_json` when some value has
/// no single static type (empty lists, nulls, mixed lists), which is represented as
/// `serde_json::Value`. Dates are kept as `String`.
pub fn generate(schema: &Schema) -> String {
    let order = schema.ordered();
    let renderer = Renderer {
        schema,
        names: order
            .iter()
            .map(|&id| type_ident(&schema.class(id).name))
            .collect(),
    };

    let mut out =
        String::from("// This file was generated by heracless. Do not edit it by hand.\n");
    let needs_json = order
        .iter()
        .any(|&id| schema.class(id).fields.iter().any(|f| uses_dynamic(&f.ty)));
    if needs_json {
        out.push_str("// Requires the `serde_json` crate for dynamically typed values.\n");
    }

    for id in order {
        let class = schema.class(id);
        let _ = write!(
            out,
            "\n#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]\npub struct {} {{\n",
            type_ident(&class.name)
        );
        for field in &class.fields {
            let ident = field_ident(&field.name);
            if ident.trim_start_matches("r#") != field.key {
                let _ = writeln!(out, "    #[serde(rename = {:?})]", field.key);
            }
            let ty = renderer.render(&field.ty);
            if ty.starts_with("Option<") || ty.starts_with("::std::option::Option<") {
                out.push_str("    #[serde(default)]\n");
            }
            let _ = writeln!(out, "    pub {ident}: {ty},");
        }
        out.push_str("}\n");
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::value::Value;
    use crate::yaml::parse_str;
    use pretty_assertions::assert_eq;

    fn rust(src: &str) -> String {
        let Value::Map(map) = parse_str(src).unwrap() else {
            panic!()
        };
        generate(&Schema::infer(&map))
    }

    #[test]
    fn structs_with_renames_and_options() {
        let out = rust("bill-to:\n  type: x\n  self: y\nitems:\n  - {a: 1}\n  - {}\n");
        assert_eq!(
            out,
            "// This file was generated by heracless. Do not edit it by hand.

#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]
pub struct Config {
    #[serde(rename = \"bill-to\")]
    pub bill_to: BillTo,
    pub items: Vec<ItemsItem>,
}

#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]
pub struct BillTo {
    pub r#type: String,
    #[serde(rename = \"self\")]
    pub self_: String,
}

#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]
pub struct ItemsItem {
    #[serde(default)]
    pub a: Option<i64>,
}
"
        );
    }

    #[test]
    fn shadowed_std_types_are_qualified() {
        let out = rust("option: {a: ~}\nname: x\n");
        assert!(out.contains("pub struct Option {"));
        assert!(out.contains("pub a: ::std::option::Option<serde_json::Value>,"));
        assert!(out.contains("pub name: String,"));
    }
}
